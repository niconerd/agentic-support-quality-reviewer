const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const staticDir = path.join(__dirname, '../reviewer/static');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(staticDir, 'json-view.js'), 'utf8'), context);
const { renderJson } = context;
const output = renderJson({'': false, nested: {list: [null, 12, 'hello']}, empty: [], note: 'long '.repeat(40), '<img onerror=alert(1)>': '</script><script>alert(1)</script>'});
assert.ok(output.startsWith('<div>{</div>'), 'Root stays expanded');
assert.equal((output.match(/<details /g) || []).length, 3, 'Nested object, list, and long text are collapsible');
assert.doesNotMatch(output, /<details[^>]*\bopen\b/, 'All child nodes start collapsed');
assert.match(output, /json-key">&quot;&quot;<\/span>: <span class="json-literal">false/);
assert.match(output, /json-literal">null/);
assert.match(output, /json-literal">12/);
assert.match(output, /json-string">&quot;hello&quot;/);
assert.match(output, /&quot;empty&quot;<\/span>: \[\]/);
assert.doesNotMatch(output, /<img|<script/, 'Keys and values cannot inject markup');
assert.match(output, /&lt;img/);
const html = fs.readFileSync(path.join(staticDir, 'index.html'), 'utf8');
assert.doesNotMatch(html, /raw-case-data|Explore example/, 'No embedded example dataset');
const sample = JSON.parse(fs.readFileSync(path.join(__dirname, '../data/tau3-retail-50.json'), 'utf8'))[0];
assert.equal(sample.id, 'tau3-retail-000');
assert.match(renderJson(sample), /&quot;initial_state&quot;/);
assert.match(renderJson(sample), /&quot;final_state&quot;/);
console.log('JSON viewer checks passed: expanded root, collapsed children, types, escaping, and real dataset data.');
